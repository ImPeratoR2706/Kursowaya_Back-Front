def insert_paragraphs_after(doc: Document, paragraph_index: int, paragraphs: list[str]) -> None:
    """
    Inserts plain-text paragraphs after a given paragraph index.
    Uses low-level XML insertion to preserve the rest of the document.
    """
    after = doc.paragraphs[paragraph_index]
    anchor = after._p  # noqa: SLF001 (python-docx internal API)
    for text in paragraphs:
        p = after._parent.add_paragraph(text)  # noqa: SLF001
        anchor.addnext(p._p)  # noqa: SLF001
        anchor = p._p  # noqa: SLF001


